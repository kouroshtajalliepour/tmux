#!/usr/bin/env bash
# Shared by the preview scripts (sourced, not run). The preview browser is
# a separate Firefox (profile "dev", window class firefox-dev) that i3
# keeps on workspace 10 (alt+0), with one tab per project. It has no key of its
# own: the lone alt tap (scripts/alt_toggle.sh), prefix+o and prefix+f take
# you there, showing the project's tab (tabs.py, over the local Marionette port).

PREVIEW_WS=10
PREVIEW_CLASS=firefox-dev
PREVIEW_PROFILE=dev
PREVIEW_REGISTRY=${PREVIEW_REGISTRY:-$HOME/.jarvis/session-bios.tsv}
PREVIEW_TABS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/tabs.py"

preview_msg() {
  tmux display-message ${TMUX_CLIENT:+-c "$TMUX_CLIENT"} "$1" 2>/dev/null || notify-send "preview" "$1"
}

port_listening() {
  ss -ltnH "( sport = :$1 )" 2>/dev/null | grep -q .
}

# Firefox's profiles.ini lives in either place depending on the version
firefox_has_profile() {
  local ini
  for ini in "$HOME/.config/mozilla/firefox/profiles.ini" "$HOME/.mozilla/firefox/profiles.ini"; do
    grep -qx "Name=$1" "$ini" 2>/dev/null && return 0
  done
  return 1
}

# Show $1 in the preview browser on workspace 10, in that project's own tab.
# An existing tab is only focused, never reloaded, so the page keeps its state.
# PREVIEW_GOTO=1 (a picker's Enter) takes it to the exact bios address instead.
open_in_preview() {
  local url=$1 win
  # PREVIEW_NO_OPEN=1: stop before touching the screen (for testing)
  [ -n "$PREVIEW_NO_OPEN" ] && { echo "would open $url"; return 0; }
  if ! command -v xdotool >/dev/null; then
    preview_msg "the preview needs xdotool: sudo pacman -S xdotool"
    return 1
  fi
  win=$(xdotool search --class "$PREVIEW_CLASS" 2>/dev/null | tail -1)
  i3-msg -q workspace number "$PREVIEW_WS"
  if [ -n "$win" ]; then
    xdotool windowactivate "$win"
    python3 -I "$PREVIEW_TABS" "$([ -n "$PREVIEW_GOTO" ] && echo goto || echo show)" "$url" >/dev/null 2>&1
    case $? in
    0) ;;
    3) preview_msg "preview: close the preview Firefox once so it restarts with tab control" ;;
    *) preview_msg "preview: couldn't switch to the tab for $url" ;;
    esac
  else
    firefox_has_profile "$PREVIEW_PROFILE" || firefox -CreateProfile "$PREVIEW_PROFILE" >/dev/null 2>&1
    setsid -f firefox --new-instance -P "$PREVIEW_PROFILE" --class "$PREVIEW_CLASS" --marionette "$url" >/dev/null 2>&1
  fi
}

# Writes $1/vite.preview.config.mjs: the project's own Vite config plus a
# plugin that sets the page title to $PREVIEW_TITLE (the branch). Adds it to
# the repo's local git exclude, so it never shows up in a diff or a commit.
BRANCH_TITLE_CONFIG=vite.preview.config.mjs
write_branch_title_config() {
  local dir=$1 base="" f exclude
  for f in vite.config.ts vite.config.mts vite.config.js vite.config.mjs; do
    [ -f "$dir/$f" ] && base=$f && break
  done
  exclude=$(git -C "$dir" rev-parse --path-format=absolute --git-path info/exclude 2>/dev/null) || return 1
  mkdir -p "$(dirname "$exclude")"
  grep -qxF "$BRANCH_TITLE_CONFIG" "$exclude" 2>/dev/null || printf '%s\n' "$BRANCH_TITLE_CONFIG" >>"$exclude"
  {
    echo '// Generated by ~/.config/tmux/scripts/preview: the tab shows the branch. Not part of the project.'
    echo 'import { defineConfig, mergeConfig } from "vite";'
    [ -n "$base" ] && echo "import base from \"./$base\";" || echo 'const base = {};'
    cat <<'EOF'
const title = (process.env.PREVIEW_TITLE || "")
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
export default defineConfig(async (env) =>
  mergeConfig(typeof base === "function" ? await base(env) : base, {
    plugins: [{
      name: "preview-branch-title",
      transformIndexHtml: (html) =>
        title ? html.replace(/<title>[^<]*<\/title>/, `<title>${title}</title>`) : html,
    }],
  }),
);
EOF
  } >"$dir/$BRANCH_TITLE_CONFIG"
}

# The session whose preview runs on port $1, from the registry.
session_for_port() {
  awk -F'\t' -v p="$1" '$0 !~ /^#/ && $3 == p { print $1; exit }' "$PREVIEW_REGISTRY" 2>/dev/null
}

# The port of the registered preview for session $1.
port_for_session() {
  awk -F'\t' -v s="$1" '$0 !~ /^#/ && $1 == s { print $3; exit }' "$PREVIEW_REGISTRY" 2>/dev/null
}
